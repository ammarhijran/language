// Regenerates js/languages/meta.js from the language packs:
//   node scripts/lang-meta.mjs
// The app shows names, flags and counts for every language (language picker,
// sync preview, achievements) without loading the packs themselves; a test
// (tests/content.test.js) fails when this table is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { languages } from '../tests/all-languages.js';

export const metaOf = (L) => ({
  code: L.code, name: L.name, nativeName: L.nativeName, flag: L.flag,
  words: L.words.length, topics: L.categories.length, alphabet: L.alphabet.length,
  grammar: (L.grammar || []).map((l) => l.id),
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const table = Object.fromEntries(Object.values(languages).map((L) => [L.code, metaOf(L)]));
  writeFileSync(new URL('../js/languages/meta.js', import.meta.url), `// GENERATED by scripts/lang-meta.mjs — do not edit by hand.
// What the app needs to know about every language without loading its pack.
export const meta = ${JSON.stringify(table, null, 2)};
`);
  console.log('meta.js written:', Object.values(table).map((m) => `${m.code} ${m.words}`).join(', '));
}

  "— مِنْ أَيْنَ تَبْدَأُ الْجَوْلَةُ؟ — مِنْ أَمَامِ الْبَابِ الرَّئِيسِيِّ.": "min ʾayna tabdaʾu-l-jawla min ʾamāmi-l-bābi-r-raʾīsī",
  "— مَا تَارِيخُ الْيَوْمِ؟ — الْخَامِسُ مِنْ مَايُو.": "mā tārīkhu-l-yawm al-khāmisu min māyū",
  "— أُرِيدُ أَنْ أَحْجِزَ مَوْعِدًا مَعَ الطَّبِيبِ. — هَلْ يُنَاسِبُكَ يَوْمُ الثُّلَاثَاءِ؟": "ʾurīdu ʾan ʾaḥjiza mawʿidan maʿa-ṭ-ṭabīb hal yunāsibuka yawmu-th-thulāthāʾ",
  "— هَلْ يُنَاسِبُكَ هَذَا الْمَوْعِدُ؟ — نَعَمْ، يُنَاسِبُنِي تَمَامًا.": "hal yunāsibuka hādhā-l-mawʿid naʿam yunāsibunī tamāman",
  "— أُرِيدُ أَنْ أَقُصَّ شَعْرِي. — تَفَضَّلْ، كَيْفَ تُرِيدُهُ؟": "ʾurīdu ʾan ʾaquṣṣa shaʿrī tafaḍḍal kayfa turīduh",
  "— كَيْفَ تُرِيدُ شَعْرَكَ؟ — لَا أُرِيدُهُ قَصِيرًا جِدًّا.": "kayfa turīdu shaʿrak lā ʾurīduhu qaṣīran jiddan",
  "— مَتَى سَيَكُونُ جَاهِزًا؟ — غَدًا بَعْدَ الظُّهْرِ.": "matā sayakūnu jāhiz ghadan baʿda-ẓ-ẓuhr",
  "— هَلْ أَنْتَ مِنْ هُنَا؟ — لَا، أَنَا مِنَ الْإِسْكَنْدَرِيَّةِ.": "hal ʾanta min hunā lā ʾanā mina-l-ʾiskandariyya",
  "— مَاذَا تَفْعَلُ فِي وَقْتِ فَرَاغِكَ؟ — أَلْعَبُ كُرَةَ الْقَدَمِ وَأَقْرَأُ كَثِيرًا.": "mādhā tafʿalu fī waqti farāghik ʾalʿabu kurata-l-qadami wa-ʾaqraʾu kathīran",
  "عِنْدَ ابْنِي حُمَّى مُنْذُ أَمْسِ.": "ʿinda-bnī ḥummā mundhu ʾams",
